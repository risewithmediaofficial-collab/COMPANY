export const Star = React.forwardRef(function StarIcon(
  { size, strokeWidth: _strokeWidth, className = '', style, color = 'inherit', ...rest },
  ref
) {
  const isFilled = /\bfill-/.test(className);
  const Component = isFilled ? StarFilled : StarBorderOutlined;
  const dimension =
    size !== undefined && size !== null
      ? typeof size === 'number'
        ? `${size}px`
        : size
      : undefined;
  const mergedStyle = dimension
    ? { fontSize: dimension, width: dimension, height: dimension, ...style }
    : style;

  return (
    <Component
      ref={ref}
      color={color}
      className={`inline-block align-middle shrink-0 ${className}`.trim()}
      style={mergedStyle}
      {...rest}
    />
  );
});
Star.displayName = 'Star';

