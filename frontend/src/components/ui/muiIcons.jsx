/**
 * Monochrome Material UI Icon Adapter
 * Wraps @mui/icons-material SVGs with crisp alignment, size prop forwarding,
 * strokeWidth cleanup, and currentColor inheritance for black/grey CRM UI.
 */
function createMuiIcon(MuiIcon, displayName) {
  const AdaptedIcon = React.forwardRef(function AdaptedMuiIcon(
    { size, strokeWidth: _strokeWidth, className = '', style, color = 'inherit', ...rest },
    ref
  ) {
    const dimension =
      size !== undefined && size !== null
        ? typeof size === 'number'
          ? `${size}px`
          : size
        : undefined;

    const mergedStyle = dimension
      ? { fontSize: dimension, width: dimension, height: dimension, ...style }
      : style;

    return (
      <MuiIcon
        ref={ref}
        color={color}
        className={`inline-block align-middle shrink-0 ${className}`.trim()}
        style={mergedStyle}
        {...rest}
      />
    );
  });

  AdaptedIcon.displayName = displayName;
  return AdaptedIcon;
}

